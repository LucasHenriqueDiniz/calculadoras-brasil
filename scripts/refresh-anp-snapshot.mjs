/**
 * Refreshes src/data/anp-weekly-snapshot.ts from the ANP's latest weekly survey
 * of pump prices: every state's average for gasoline and hydrated ethanol.
 *
 *   node scripts/refresh-anp-snapshot.mjs
 *
 * The /calculadora-custo-carro table is built from this file at prerender, so the
 * page carries a dated survey instead of fetching gov.br during the build. After
 * running it, move that page's lastmod in src/lib/seo-pages.ts.
 *
 * The adapter is TypeScript with extensionless imports, so it is loaded through
 * Vite's SSR loader rather than by Node directly.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import { createServer } from "vite";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const TARGET = `${ROOT}src/data/anp-weekly-snapshot.ts`;

const server = await createServer({
  root: ROOT,
  configFile: false,
  logLevel: "error",
  appType: "custom",
  server: { middlewareMode: true, hmr: false },
  resolve: { alias: { "@": `${ROOT}src` } },
});

try {
  const { fetchAnpPricesByState } = await server.ssrLoadModule("/src/server/adapters/anp.ts");
  const results = await fetchAnpPricesByState(["gasolina", "etanol"]);

  const periods = new Set(results.map((result) => result.period));
  if (periods.size !== 1) {
    throw new Error(`Expected one survey week, found: ${[...periods].join(", ")}`);
  }
  const [periodStart, periodEnd] = [...periods][0].split(" a ");
  const sourceUrl = results[0].sourceUrl;

  const ufs = [...new Set(results.map((result) => result.uf))];
  const priceOf = (uf, fuel) =>
    results.find((result) => result.uf === uf && result.fuel === fuel)?.averagePrice ?? null;
  const states = ufs.map((uf) => ({
    uf,
    gasoline: priceOf(uf, "gasolina"),
    ethanol: priceOf(uf, "etanol"),
  }));

  const source = `/**
 * GENERATED by scripts/refresh-anp-snapshot.mjs. Do not edit by hand: re-run it.
 *
 * State averages from the ANP's weekly survey of pump prices, the week of
 * ${periodStart} to ${periodEnd}. The /calculadora-custo-carro table is built from it.
 */
export const ANP_WEEKLY_SNAPSHOT = ${JSON.stringify({ periodStart, periodEnd, sourceUrl, states }, null, 2)} as const;
`;
  const options = (await prettier.resolveConfig(TARGET)) ?? {};
  await writeFile(TARGET, await prettier.format(source, { ...options, filepath: TARGET }));

  const missing = states.filter((state) => state.gasoline === null || state.ethanol === null);
  console.log(
    `Wrote ${states.length} states for ${periodStart} to ${periodEnd}` +
      (missing.length ? `; missing a price: ${missing.map((s) => s.uf).join(", ")}` : "."),
  );
} finally {
  await server.close();
}
